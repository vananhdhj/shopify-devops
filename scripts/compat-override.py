#!/usr/bin/env python3
"""Writes a Compose override that runs the previous release's cell images (ADR-0021).

While a release moves through the waves, the last wave still runs the release before it, on the
schema the new release migrated to, behind the new control plane and edge. This override pins the
cell's long-running units (catalog API, order service, worker, storefront) to the digests the last
wave runs on main, from GHCR; everything else, the migrations, the control plane, and the edge, is
built from the working tree as usual.
    compat-override.py [cells-dir] > override.yaml
"""
import json
import re
import sys
from pathlib import Path

CELL_UNITS = ["catalog-cart-api", "order-service", "worker", "storefront"]

cells_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "deploy/cells/dev")
cells = [(json.loads(path.read_text()), path.parent) for path in sorted(cells_dir.glob("*/cell.json"))]
last_wave = max(cell["wave"] for cell, _ in cells)
cell, directory = next((cell, directory) for cell, directory in cells if cell["wave"] == last_wave)

pins = dict(re.findall(r"-\s*name:\s*(\S+)\s*\n\s*digest:\s*(sha256:[0-9a-f]{64})", (directory / "kustomization.yaml").read_text()))
lines = [
    f"# Generated by scripts/compat-override.py: the cell units of {cell['cell']} (wave {last_wave}) as pinned on this",
    "# checkout, pulled from GHCR; migrations, the control plane, and the edge are built from the tree.",
    "services:",
]
for unit in CELL_UNITS:
    image = next((name for name in pins if name.rsplit("/", 1)[-1] == unit), None)
    if image is None:
        sys.exit(f"compat-override: {directory}/kustomization.yaml pins no {unit} image")
    lines += [f"  {unit}:", f"    image: {image}@{pins[image]}", "    build: !reset null", "    pull_policy: missing"]
    print(f"compat: {unit} from {cell['cell']} (wave {last_wave}): {pins[image][:19]}", file=sys.stderr)
print("\n".join(lines))
